-- Supabase 게시판 초기 데이터베이스 구성
-- 새 Supabase 프로젝트에서 실행하세요.
-- 이미 같은 이름의 테이블·함수·정책·트리거가 있으면 자동으로 덮어쓰지 않습니다.
-- 기존 객체의 열, 제약조건, 정책 정의가 이 파일과 다른 경우에는 내용을 확인한 뒤 별도 수정 SQL을 작성하세요.

begin;

-- =========================================================
-- 1. 게시글과 댓글 테이블
-- =========================================================

create table if not exists public.posts (
  id bigint generated by default as identity primary key,
  user_id uuid not null default auth.uid() references auth.users(id),
  title text not null,
  content text not null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint posts_title_length_check check (char_length(title) between 1 and 200),
  constraint posts_title_not_blank_check check (btrim(title) <> ''),
  constraint posts_content_not_blank_check check (btrim(content) <> '')
);

create table if not exists public.comments (
  id bigint generated by default as identity primary key,
  post_id bigint not null references public.posts(id) on delete cascade,
  user_id uuid not null default auth.uid() references auth.users(id),
  content text not null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint comments_content_not_blank_check check (btrim(content) <> '')
);

-- 목록과 댓글 조회에 사용하는 인덱스입니다.
create index if not exists posts_user_id_idx on public.posts (user_id);
create index if not exists posts_created_at_idx on public.posts (created_at desc);
create index if not exists comments_post_id_idx on public.comments (post_id);
create index if not exists comments_user_id_idx on public.comments (user_id);

-- =========================================================
-- 2. 권한과 RLS
-- =========================================================

grant usage on schema public to anon, authenticated;

-- 기본으로 남아 있을 수 있는 테이블 권한을 먼저 회수합니다.
revoke all on table public.posts from anon, authenticated;
revoke all on table public.comments from anon, authenticated;

-- 비로그인 사용자도 게시글과 댓글은 읽을 수 있습니다.
grant select on table public.posts to anon, authenticated;
grant select on table public.comments to anon, authenticated;

-- 로그인한 사용자만 작성·삭제할 수 있습니다.
-- UPDATE는 실제로 바꿀 수 있는 일반 열에만 허용합니다.
grant insert, delete on table public.posts to authenticated;
grant update (title, content) on table public.posts to authenticated;
grant insert, delete on table public.comments to authenticated;
grant update (content) on table public.comments to authenticated;

alter table public.posts enable row level security;
alter table public.comments enable row level security;

-- 정책은 이미 있을 경우 덮어쓰지 않습니다.
-- 새 프로젝트에서는 아래 정책들이 모두 생성됩니다.
do $$
begin
  if not exists (select 1 from pg_catalog.pg_policy where polrelid = 'public.posts'::regclass and polname = 'posts_select_all') then
    execute 'create policy posts_select_all on public.posts for select to anon, authenticated using (true)';
  end if;
  if not exists (select 1 from pg_catalog.pg_policy where polrelid = 'public.posts'::regclass and polname = 'posts_insert_own') then
    execute 'create policy posts_insert_own on public.posts for insert to authenticated with check ((select auth.uid()) = user_id)';
  end if;
  if not exists (select 1 from pg_catalog.pg_policy where polrelid = 'public.posts'::regclass and polname = 'posts_update_own') then
    execute 'create policy posts_update_own on public.posts for update to authenticated using ((select auth.uid()) = user_id) with check ((select auth.uid()) = user_id)';
  end if;
  if not exists (select 1 from pg_catalog.pg_policy where polrelid = 'public.posts'::regclass and polname = 'posts_delete_own') then
    execute 'create policy posts_delete_own on public.posts for delete to authenticated using ((select auth.uid()) = user_id)';
  end if;

  if not exists (select 1 from pg_catalog.pg_policy where polrelid = 'public.comments'::regclass and polname = 'comments_select_all') then
    execute 'create policy comments_select_all on public.comments for select to anon, authenticated using (true)';
  end if;
  if not exists (select 1 from pg_catalog.pg_policy where polrelid = 'public.comments'::regclass and polname = 'comments_insert_own') then
    execute 'create policy comments_insert_own on public.comments for insert to authenticated with check ((select auth.uid()) = user_id)';
  end if;
  if not exists (select 1 from pg_catalog.pg_policy where polrelid = 'public.comments'::regclass and polname = 'comments_update_own') then
    execute 'create policy comments_update_own on public.comments for update to authenticated using ((select auth.uid()) = user_id) with check ((select auth.uid()) = user_id)';
  end if;
  if not exists (select 1 from pg_catalog.pg_policy where polrelid = 'public.comments'::regclass and polname = 'comments_delete_own') then
    execute 'create policy comments_delete_own on public.comments for delete to authenticated using ((select auth.uid()) = user_id)';
  end if;
end;
$$;

-- =========================================================
-- 3. 수정 시각 갱신과 변경 금지 트리거
-- =========================================================

-- 함수가 없을 때만 만듭니다. 기존 함수를 자동으로 바꾸지 않습니다.
do $$
begin
  if not exists (
    select 1 from pg_catalog.pg_proc p
    join pg_catalog.pg_namespace n on n.oid = p.pronamespace
    where n.nspname = 'public' and p.proname = 'set_updated_at' and p.pronargs = 0
  ) then
    execute $function$
      create function public.set_updated_at()
      returns trigger
      language plpgsql
      set search_path = ''
      as $body$
      begin
        new.updated_at := pg_catalog.now();
        return new;
      end;
      $body$
    $function$;
  end if;

  if not exists (
    select 1 from pg_catalog.pg_proc p
    join pg_catalog.pg_namespace n on n.oid = p.pronamespace
    where n.nspname = 'public' and p.proname = 'prevent_post_user_change' and p.pronargs = 0
  ) then
    execute $function$
      create function public.prevent_post_user_change()
      returns trigger
      language plpgsql
      set search_path = ''
      as $body$
      begin
        if new.user_id is distinct from old.user_id then
          raise exception '게시글 작성자는 변경할 수 없습니다.';
        end if;
        return new;
      end;
      $body$
    $function$;
  end if;

  if not exists (
    select 1 from pg_catalog.pg_proc p
    join pg_catalog.pg_namespace n on n.oid = p.pronamespace
    where n.nspname = 'public' and p.proname = 'prevent_comment_relation_change' and p.pronargs = 0
  ) then
    execute $function$
      create function public.prevent_comment_relation_change()
      returns trigger
      language plpgsql
      set search_path = ''
      as $body$
      begin
        if new.user_id is distinct from old.user_id then
          raise exception '댓글 작성자는 변경할 수 없습니다.';
        end if;
        if new.post_id is distinct from old.post_id then
          raise exception '댓글의 게시글은 변경할 수 없습니다.';
        end if;
        return new;
      end;
      $body$
    $function$;
  end if;
end;
$$;

-- 트리거가 없을 때만 생성합니다.
do $$
begin
  if not exists (select 1 from pg_catalog.pg_trigger where tgrelid = 'public.posts'::regclass and tgname = 'posts_10_prevent_user_change') then
    execute 'create trigger posts_10_prevent_user_change before update on public.posts for each row execute function public.prevent_post_user_change()';
  end if;
  if not exists (select 1 from pg_catalog.pg_trigger where tgrelid = 'public.posts'::regclass and tgname = 'posts_20_set_updated_at') then
    execute 'create trigger posts_20_set_updated_at before update on public.posts for each row execute function public.set_updated_at()';
  end if;
  if not exists (select 1 from pg_catalog.pg_trigger where tgrelid = 'public.comments'::regclass and tgname = 'comments_10_prevent_relation_change') then
    execute 'create trigger comments_10_prevent_relation_change before update on public.comments for each row execute function public.prevent_comment_relation_change()';
  end if;
  if not exists (select 1 from pg_catalog.pg_trigger where tgrelid = 'public.comments'::regclass and tgname = 'comments_20_set_updated_at') then
    execute 'create trigger comments_20_set_updated_at before update on public.comments for each row execute function public.set_updated_at()';
  end if;
end;
$$;

-- 트리거 함수는 클라이언트가 직접 실행할 필요가 없습니다.
revoke all on function public.set_updated_at() from public, anon, authenticated;
revoke all on function public.prevent_post_user_change() from public, anon, authenticated;
revoke all on function public.prevent_comment_relation_change() from public, anon, authenticated;

-- 참고: 테이블 소유자, postgres, service_role처럼 RLS를 우회할 수 있는 높은 권한은
-- 이 정책의 제한을 받지 않을 수 있습니다. 웹 브라우저에는 Publishable key만 사용하세요.

commit;
